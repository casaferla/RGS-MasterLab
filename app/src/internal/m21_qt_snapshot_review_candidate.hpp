inline QString as_qstring(const std::string& str) {
    return QString::fromStdString(str);
}
inline QVariantMap masked_unpublished_envelope() {
    return {
        {"ready",false},
        {"analysisStatus",QStringLiteral("MISSING")},
        {"fixtureMode",false},
        {"productionAuthorized",false},
        {"scopeLabel",QStringLiteral("SCOPE UNAVAILABLE")},
        {"spectrumStatus",QStringLiteral("UNAVAILABLE")},
        {"tonalProfileStatus",QStringLiteral("UNAVAILABLE")},
        {"levels",QVariantMap{}},
        {"stereo",QVariantMap{}},
        {"metrics",QVariantList{}},
        {"spectrum",QVariantList{}},
        {"bands",QVariantList{}}
    };
}
// This is intended exclusively for the isolated Qt screenshot/test harness.
// It does not assert that external owner receipt CLAIMS are canonical proof.
struct ExplicitTestFixture final {
    explicit ExplicitTestFixture(std::uint32_t x) : test_marker(x) {}
    std::uint32_t test_marker{};
};
inline QVariantMap candidate_test_fixture_envelope(
    const ReadOnlyProjection& projection,
    Column display_column,
    ExplicitTestFixture test_only)
{
    auto out=masked_unpublished_envelope();
    // The magic marker is a test harness constant, not an authentication
    // token. It MUST NEVER be used for real Product result publication.
    if(test_only.test_marker!=0x4D323147U ||
       projection.production_authorized)
        return out;
    const std::size_t column=static_cast<std::size_t>(display_column);
    if(column>=projection.columns.size())return out;
    const auto& selected=projection.columns[column];
    out.insert("fixtureMode",true); // screenshot watermark, never Product
    out.insert("analysisStatus",as_qstring(selected.state));
    out.insert("scopeLabel",as_qstring(selected.scope_text));
    out.insert("goldIndependentScope",projection.gold_independent_scope);
    // Spectrum/normalized shape is NOT generated by this presentation mapper.
    // A missing PSD must not be drawn as a measured flat response.
    out.insert("spectrumStatus",QStringLiteral("UNAVAILABLE"));
    out.insert("tonalProfileStatus",QStringLiteral("UNAVAILABLE"));
    // This only asserts an independently matched PREPRODUCTION receipt and
    // is allowed inside the explicit screenshot/test fixture context.
    out.insert("ready",selected.candidate_matched);
    if(!selected.candidate_matched)return out;
    const auto string_cell=[&](const ReadOnlyCell& c)->QVariant {
        return as_qstring(c.value_text);
    };
    QVariantMap levels{
        {"lufs",string_cell(selected.values[0])},
        {"rms",string_cell(selected.values[1])},
        {"samplePeak",string_cell(selected.values[2])},
        {"truePeak",QStringLiteral("UNAVAILABLE")},
        {"crest",string_cell(selected.values[4])}
    };
    QVariantMap stereo{
        {"width",string_cell(selected.values[5])},
        {"P10",string_cell(selected.values[6])},
        {"P50",string_cell(selected.values[7])},
        {"P90",string_cell(selected.values[8])}
    };
    out.insert("levels",levels);
    out.insert("stereo",stereo);
    static constexpr std::array<const char*,3> columnKeys{{
        "prepared","gold","processed"
    }};
    QVariantList rows;
    for(std::size_t metric=0;metric<kMetricSpecs.size();++metric) {
        QVariantMap row;
        row.insert("name",QString::fromLatin1(kMetricSpecs[metric].name));
        for(std::size_t col=0;col<3;++col) {
            const auto& cell=projection.columns[col].values[metric];
            const auto base=QString::fromLatin1(columnKeys[col]);
            const auto visible=projection.columns[col].candidate_matched;
            row.insert(base,visible?string_cell(cell):
                        QVariant(QStringLiteral("UNAVAILABLE")));
            row.insert(base+"Quality",as_qstring(
                visible?cell.quality_text:projection.columns[col].state));
        }
        const auto& p=projection.prepared_to_gold[metric];
        const auto& x=projection.processed_to_gold[metric];
        row.insert("preparedDelta",string_cell(p));
        row.insert("processedDelta",string_cell(x));
        row.insert("preparedDeltaQuality",as_qstring(p.quality_text));
        row.insert("processedDeltaQuality",as_qstring(x.quality_text));
        row.insert("unit",QString::fromLatin1(
            kMetricSpecs[metric].absolute_unit));
        rows.push_back(row);
    }
    out.insert("metrics",rows);
    return out;
}
